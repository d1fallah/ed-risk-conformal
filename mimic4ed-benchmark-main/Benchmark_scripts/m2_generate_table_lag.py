"""
Phase 4 -- LaTeX booktabs table for the label-lag experiment (M2_LabelLag_PreRegistration.md).
Reads data/m2_v2_label_lag.csv (written by m2_label_lag.py) and writes paper_assets/tables/label_lag.tex.
Hybrid GRU-D v2 (primary), 5-seed means. Every number is read from the CSV; nothing is typed here.
Hour equivalents are a coarse conversion at ~5 arrivals/hour (uncertain by +/-50%; dates are shifted,
so the rate cannot be measured from the data) and are labelled as such in the caption.
"""
import os
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
CSV = os.path.join(HERE, "..", "data", "m2_v2_label_lag.csv")
OUT = os.path.join(HERE, "..", "paper_assets", "tables", "label_lag.tex")
PRIMARY = "Hybrid GRU-D v2"
LAGS = ["0", "60", "240", "1000", "4000", "16000", "inf"]
HOURS = {"0": "0", "60": "$\\approx$12\\,h", "240": "$\\approx$2\\,d", "1000": "$\\approx$8\\,d",
         "4000": "$\\approx$33\\,d", "16000": "$\\approx$4.4\\,mo", "inf": "never"}
LAGCELL = {L: ("$\\infty$" if L == "inf" else f"{int(L):,}".replace(",", "{,}")) for L in LAGS}


def main():
    d = pd.read_csv(CSV, dtype={"lag": str})
    d = d[d.model == PRIMARY]
    mg = d[d.family == "marginal"].groupby(["lag", "method"])[["coverage", "size"]].mean()
    cl = d[d.family == "class"].groupby(["lag", "method"])[["coverage_class0", "coverage_class1", "size", "informative_class1"]].mean()

    a = cl.loc[("0", "A")]
    A_TXT = f"{a.coverage_class0:.3f} / {a.coverage_class1:.3f} / {a['size']:.3f}"
    L = [
        "% Auto-generated by m2_generate_table_lag.py from data/m2_v2_label_lag.csv -- do not hand-edit.",
        "% Hybrid GRU-D v2, mean over 5 confirmatory seeds, chronological-primary split, alpha=0.1.",
        "\\begin{table}[H]",
        "\\centering",
        "\\caption{Label lag (Sec.24.3d; pre-registered in \\texttt{M2\\_LabelLag\\_PreRegistration.md}), Hybrid GRU-D v2 (Proxy: MIMIC-IV-ED). "
        "Lag $L$ is in arrivals; hour equivalents assume $\\sim$5 arrivals/hour and are approximate ($\\pm$50\\%). "
        "\\emph{Marginal:} coverage / mean clipped interval width for ECI (M2) and static split-conformal with periodic recalibration (M3: $W$=10k; M4: $W$=40k). "
        "Valid means coverage $\\geq$ 0.89; ECI is not needed if a valid recalibration is at most 0.02 wider. "
        "At $L\\geq$ 4{,}000 ECI's radius winds up on stale feedback and over-covers with near-vacuous intervals, and at $L=\\infty$ nothing is valid. "
        "Realistic band (pre-registered): $L\\in\\{60,240,1000\\}$. Labels are otherwise assumed uniform-lag; ECI's lr is re-selected per lag on the calibration-selection fold.}",
        "\\label{tab:m2-label-lag-marginal}",
        "\\resizebox{\\textwidth}{!}{%",
        "\\begin{tabular}{llccc}",
        "\\toprule",
        "$L$ (arrivals) & $\\approx$ time & ECI (M2) & recal.\\ $W$=10k (M3) & recal.\\ $W$=40k (M4) \\\\",
        "\\midrule",
    ]
    for lag in LAGS:
        cells = [f"{mg.loc[(lag, m), 'coverage']:.4f} / {mg.loc[(lag, m), 'size']:.3f}" for m in ("M2", "M3", "M4")]
        L.append(f"{LAGCELL[lag]} & {HOURS[lag]} & " + " & ".join(cells) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}%", "}", "\\end{table}", "",
          "\\begin{table}[H]", "\\centering",
          "\\caption{Label lag, class-conditional (Mondrian) sets, Hybrid GRU-D v2 (Proxy: MIMIC-IV-ED). Class-0 / class-1 coverage, mean $|C|$ and the informative "
          "rate $P(C{=}\\{1\\}\\mid y{=}1)$ for Mondrian-ECI (B) and static Mondrian with periodic recalibration (C1: $W$=10k). Valid means both coverages $\\geq$ 0.89. "
          "Mondrian-ECI's sets grow with lag (its class-1 radius saturates), while recalibration is essentially unchanged; from $L=4{,}000$ Mondrian-ECI loses validity. "
          "The static anchor (A) is unaffected by lag: " + A_TXT + " (not valid).}",
          "\\label{tab:m2-label-lag-class}",
          "\\resizebox{\\textwidth}{!}{%",
          "\\begin{tabular}{llcccc}",
          "\\toprule",
          "$L$ (arrivals) & $\\approx$ time & B: cov$_0$ / cov$_1$ & B: $|C|$ & B: informative & C1: cov$_0$ / cov$_1$ / $|C|$ / informative \\\\",
          "\\midrule"]
    for lag in LAGS:
        b, c = cl.loc[(lag, "B")], cl.loc[(lag, "C1")]
        L.append(f"{LAGCELL[lag]} & {HOURS[lag]} & {b.coverage_class0:.3f} / {b.coverage_class1:.3f} & {b['size']:.3f} & {b.informative_class1:.3f} & "
                 f"{c.coverage_class0:.3f} / {c.coverage_class1:.3f} / {c['size']:.3f} / {c.informative_class1:.3f} \\\\")
    L += ["\\bottomrule", "\\end{tabular}%", "}", "\\end{table}"]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(L) + "\n")
    print(f"Wrote {OUT}")
    small_ablations()


def small_ablations():
    """Logit-vs-clipping and latency: one compact table (small required-ablation re-runs, dossier Sec.24.8)."""
    import json
    lg = pd.read_csv(os.path.join(HERE, "..", "data", "m2_v2_logit_vs_clipping.csv"))
    lat = json.load(open(os.path.join(HERE, "..", "data", "m2_v2_latency.json")))
    g = lg.groupby(["model", "bounding"])[["coverage", "coverage_class1", "width"]].mean()
    hw = lat["hardware"]; P = lat["paths"]
    T = [
        "% Auto-generated by m2_generate_table_lag.py from data/m2_v2_logit_vs_clipping.csv and data/m2_v2_latency.json -- do not hand-edit.",
        "\\begin{table}[H]",
        "\\centering",
        "\\caption{Small required-ablation re-runs on the v2 primary split (Sec.24.8; Proxy: MIMIC-IV-ED). "
        "\\emph{Logit vs.\\ clipping:} marginal coverage / class-1 coverage / mean width of the same ECI radius under each bounding, 5-seed means. "
        "The logit-bounded interval lies strictly inside $(0,1)$ and so cannot contain a hard label: its coverage is 0 by construction. "
        f"\\emph{{Latency:}} batch size 1, 2{{,}}000 timed calls, Hybrid GRU-D v2 seed 42, {hw['gpu']} and {hw['cpu_count']} logical CPUs; "
        "hardware- and load-dependent, this machine only; Track B service path not measured. Budget: 2{,}000\\,ms per patient update.}",
        "\\label{tab:m2-small-ablations}",
        "\\resizebox{\\textwidth}{!}{%",
        "\\begin{tabular}{lccc}",
        "\\toprule",
        "Model & bounding & coverage / class-1 coverage & width \\\\",
        "\\midrule",
    ]
    for (model, bnd), r in g.iterrows():
        T.append(f"{model.replace(' v2', '')} & {bnd} & {r.coverage:.4f} / {r.coverage_class1:.4f} & {r.width:.4f} \\\\")
    T += ["\\midrule", "Latency path & \\multicolumn{3}{c}{median / p95 / p99 / max (ms) or amortized per arrival} \\\\", "\\midrule"]
    for key, name in (("forward_gpu", "forward pass, GPU"), ("forward_cpu", "forward pass, CPU"),
                      ("end_to_end_gpu_forward_plus_eci", "end to end: GPU forward + ECI step + set")):
        v = P[key]
        T.append(f"{name} & \\multicolumn{{3}}{{c}}{{{v['median_ms']:.2f} / {v['p95_ms']:.2f} / {v['p99_ms']:.2f} / {v['max_ms']:.1f}}} \\\\")
    for key, name in (("split_conformal_set", "split-conformal set"), ("eci_step_plus_set", "ECI step + set"),
                      ("mondrian_eci_step_plus_set", "Mondrian-ECI step + set")):
        T.append(f"{name} & \\multicolumn{{3}}{{c}}{{{P[key]['amortized_ms_per_arrival']:.4f} per arrival}} \\\\")
    T += ["\\bottomrule", "\\end{tabular}%", "}", "\\end{table}"]
    out = os.path.join(HERE, "..", "paper_assets", "tables", "small_ablations.tex")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(T) + "\n")
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
