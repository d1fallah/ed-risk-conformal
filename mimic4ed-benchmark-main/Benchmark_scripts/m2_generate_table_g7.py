"""
G7 clinician-facing conformal decision table (Phase 4 of the session's
"Clearing the Runway to the Manuscript" plan). IEEE JBHI priority per the
plan's venue framing.

Translates data/m2_v2_conformal_summary.csv (already-computed MAPIE / ECI /
Mondrian-LAC results on the chronological-primary split, Sec 24.3) into the
decision-relevant quantity a clinician reader actually cares about: among
patients who DO deteriorate (class 1), how often does the 90%-target
prediction set/interval fail to include that outcome -- i.e. how often does
the system give a falsely reassuring 90%-confidence signal? This is
1 - coverage_class1, reported here as "miss rate (class 1)".

No new computation beyond aggregation: reads already-saved per-seed rows,
computes mean +/- std over the 5 confirmatory seeds, emits a booktabs
LaTeX table. Never fabricates a number -- if m2_v2_conformal_summary.csv is
missing a column for a method (e.g. ECI has no empty-set concept, since it
produces a continuous interval rather than a discrete label set), that cell
is written as "--", not estimated.
"""
import os
import numpy as np
import pandas as pd

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
DATA_DIR = os.path.join(SCRIPT_DIR, "..", "data")
OUT_DIR = os.path.join(SCRIPT_DIR, "..", "paper_assets", "tables")
os.makedirs(OUT_DIR, exist_ok=True)

SRC = os.path.join(DATA_DIR, "m2_v2_conformal_summary.csv")

MODEL_ORDER = ["Temporal-Only GRU-D v2", "Frozen-Temporal Head Control v2", "Hybrid GRU-D v2"]
MODEL_LABEL = {
    "Temporal-Only GRU-D v2": "Temporal-Only GRU-D",
    "Frozen-Temporal Head Control v2": "Frozen-Temporal Head Control",
    "Hybrid GRU-D v2": "Hybrid GRU-D (primary)",
}

# (method label, coverage_class1 col, empty_set_rate_class1 col or None, width/size col)
METHODS = [
    ("MAPIE (split-conformal)", "mapie_coverage_class1", "mapie_empty_set_rate_class1", "eci_width"),
    ("ECI (adaptive)", "eci_coverage_class1", None, "eci_width"),
    ("Mondrian-LAC (label-conditional)", "mondrian_lac_coverage_class1", "mondrian_lac_empty_set_rate_class1", "mondrian_mean_set_size"),
]
# eci_width is the ECI method's own interval width; MAPIE reuses the same
# underlying score scale in this file (single eci_width column shared per
# row) so MAPIE's width cell is intentionally left "--" rather than reusing
# a number that was not computed for MAPIE's own construction.


def fmt(mean, std, pct=True, digits=1):
    if pct:
        return f"{mean*100:.{digits}f} $\\pm$ {std*100:.{digits}f}"
    return f"{mean:.3f} $\\pm$ {std:.3f}"


def main():
    df = pd.read_csv(SRC)
    rows = []
    for model in MODEL_ORDER:
        sub_model = df[df["model"] == model]
        assert len(sub_model) == 5, f"expected 5 confirmatory seeds for {model}, got {len(sub_model)}"
        for method_label, cov_col, empty_col, width_col in METHODS:
            cov = sub_model[cov_col].values
            miss = 1.0 - cov
            cov_mean, cov_std = cov.mean(), cov.std()
            miss_mean, miss_std = miss.mean(), miss.std()
            if empty_col is not None:
                empty = sub_model[empty_col].values
                empty_str = fmt(empty.mean(), empty.std())
            else:
                empty_str = "--"
            if method_label.startswith("MAPIE"):
                width_str = "--"
            else:
                width = sub_model[width_col].values
                width_str = f"{width.mean():.3f} $\\pm$ {width.std():.3f}"
            rows.append({
                "model": MODEL_LABEL[model],
                "method": method_label,
                "coverage_class1": fmt(cov_mean, cov_std),
                "miss_rate_class1": fmt(miss_mean, miss_std),
                "empty_set_rate_class1": empty_str,
                "width_or_size": width_str,
            })
            print(f"{MODEL_LABEL[model]:32s} {method_label:35s} "
                  f"cov1={cov_mean:.4f}+/-{cov_std:.4f}  miss1={miss_mean:.4f}+/-{miss_std:.4f}  "
                  f"empty1={empty_str}  width/size={width_str}")

    lines = []
    lines.append("% Auto-generated by m2_generate_table_g7.py from data/m2_v2_conformal_summary.csv -- do not hand-edit.")
    lines.append("% Mean +/- std over 5 confirmatory seeds {42,123,7,456,789}, chronological-primary split (Gate v2, Sec 24.3).")
    lines.append("% Class 1 = deterioration (the clinically actionable minority class).")
    lines.append("\\begin{table}[t]")
    lines.append("\\centering")
    lines.append("\\caption{Clinician-facing translation of Sec.24.3's conformal-coverage result (G7): "
                  "among patients who actually deteriorate (class 1), how often does each method's "
                  "90\\%-target prediction set/interval \\emph{fail} to cover that outcome (miss rate, "
                  "the falsely-reassuring case), how often does it abstain (empty-set rate), and how wide "
                  "is the interval/set on average. MAPIE (split-conformal) and ECI (adaptive) both "
                  "collapse on the minority class (class-1 coverage 3--8\\% against a 90\\% target) even "
                  "though ECI's MARGINAL coverage is near-exact; only the label-conditional Mondrian-LAC "
                  "restores class-1 coverage to near target, at the cost of larger sets. "
                  "MAPIE's width/size cell is left blank (--) rather than reusing ECI's width column, "
                  "since MAPIE's own interval width was not separately persisted per class.}")
    lines.append("\\label{tab:m2-g7-clinician-decision}")
    lines.append("\\resizebox{\\textwidth}{!}{%")
    lines.append("\\begin{tabular}{llcccc}")
    lines.append("\\toprule")
    lines.append("Model & Method & Coverage (class 1, \\%) & Miss rate (class 1, \\%) & Empty-set rate (class 1, \\%) & Width / set size \\\\")
    lines.append("\\midrule")
    prev_model = None
    for r in rows:
        model_cell = r["model"] if r["model"] != prev_model else ""
        prev_model = r["model"]
        lines.append(f"{model_cell} & {r['method']} & {r['coverage_class1']} & {r['miss_rate_class1']} & "
                      f"{r['empty_set_rate_class1']} & {r['width_or_size']} \\\\")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}%")
    lines.append("}")
    lines.append("\\end{table}")

    out_path = os.path.join(OUT_DIR, "g7_clinician_decision.tex")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"\nWrote {out_path}")


if __name__ == "__main__":
    main()
