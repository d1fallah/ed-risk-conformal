"""
M2 -- v2 LaTeX booktabs table generation (Phase 4 of the session's
"Clearing the Runway to the Manuscript" plan)
==============================================================================
Emits the separable LaTeX table files CLAUDE.md Sec 1.3/Sec 4 Step 6
requires as publication artifacts (booktabs comparison tables), mirroring
module 4's paper_assets/tables/*.tex convention (auto-generated header
comment, \\begin{table}, booktabs rules, $\\pm$ for mean+/-SD, \\label for
\\ref{} use in the manuscript skeleton). No number is computed here --
every value is read from an already-saved CSV/JSON artifact.

Four tables, all sourced from files already produced by prior v2 stages:
  headline_discrimination_v2.tex  <- data/m2_v2_results.csv (Sec 24.2)
  deltas_v2.tex                   <- data/m2_v2_deltas.json (Sec 24.2b)
  conformal_summary_v2.tex        <- data/m2_v2_conformal_summary.csv (Sec 24.3)
  news2_sensitivity.tex           <- data/m2_news2_sensitivity.csv (Sec 23 row 3)
(g7_clinician_decision.tex is emitted separately by m2_generate_table_g7.py.)
"""
import os, json
import numpy as np
import pandas as pd

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
DATA_DIR = os.path.join(SCRIPT_DIR, "..", "data")
OUT_DIR = os.path.join(SCRIPT_DIR, "..", "paper_assets", "tables")
os.makedirs(OUT_DIR, exist_ok=True)

MODEL_ORDER = ["Static-Only MLP v2", "mTAN v2", "Temporal-Only GRU-D v2",
               "Frozen-Temporal Head Control v2", "XGBoost-Matched v2", "Hybrid GRU-D v2"]
MODEL_LABEL = {
    "Static-Only MLP v2": "Static-Only MLP",
    "mTAN v2": "mTAN (tuned)",
    "Temporal-Only GRU-D v2": "Temporal-Only GRU-D",
    "Frozen-Temporal Head Control v2": "Frozen-Temporal Head Control (tuned)",
    "XGBoost-Matched v2": "XGBoost-Matched (tuned)",
    "Hybrid GRU-D v2": "\\textbf{Hybrid GRU-D (primary, tuned)}",
}
T2_AUROC = {  # for the "vs. T=2" column, Sec 24.2's own table
    "Static-Only MLP v2": 0.8488, "mTAN v2": None,
    "Temporal-Only GRU-D v2": 0.8690, "Frozen-Temporal Head Control v2": 0.8692,
    "XGBoost-Matched v2": 0.9066, "Hybrid GRU-D v2": 0.9071,
}


def write(path, lines):
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Wrote {path}")


def table_headline_discrimination():
    df = pd.read_csv(os.path.join(DATA_DIR, "m2_v2_results.csv"))
    lines = [
        "% Auto-generated by m2_generate_tables_v2.py from data/m2_v2_results.csv -- do not hand-edit.",
        "% Mean +/- std over 5 confirmatory seeds {42,123,7,456,789}, chronological-primary split (Gate v2).",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Discrimination and calibration, all 6 v2 models, irregular-series cohort, "
        "chronological-primary split (Sec.24.2). Three models (XGBoost-Matched, Frozen-Temporal Head "
        "Control, Hybrid GRU-D) are reported at their tuning-symmetric configs (Sec.24.2, Phase 2).}",
        "\\label{tab:m2-v2-headline}",
        "\\resizebox{\\textwidth}{!}{%",
        "\\begin{tabular}{lccccc}",
        "\\toprule",
        "Model & AUROC & AUPRC & Brier & ECE & vs.\\ T=2 AUROC \\\\",
        "\\midrule",
    ]
    for m in MODEL_ORDER:
        sub = df[df["model"] == m]
        assert len(sub) == 5, f"{m}: expected 5 seeds, got {len(sub)}"
        auroc_m, auroc_s = sub["auroc"].mean(), sub["auroc"].std()
        auprc_m, auprc_s = sub["auprc"].mean(), sub["auprc"].std()
        brier_m, ece_m = sub["brier"].mean(), sub["ece"].mean()
        t2 = T2_AUROC[m]
        t2_cell = "new comparator" if t2 is None else f"{t2:.4f} ({auroc_m - t2:+.4f})"
        lines.append(f"{MODEL_LABEL[m]} & {auroc_m:.4f} $\\pm$ {auroc_s:.4f} & "
                      f"{auprc_m:.4f} $\\pm$ {auprc_s:.4f} & {brier_m:.4f} & {ece_m:.4f} & {t2_cell} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}%", "}", "\\end{table}"]
    write(os.path.join(OUT_DIR, "headline_discrimination_v2.tex"), lines)


DELTA_LABEL = {
    "Delta_representation": "$\\Delta_{\\text{representation}}$ (Hybrid GRU-D $-$ XGBoost-Matched, PRIMARY)",
    "Delta_static_contribution": "$\\Delta_{\\text{static\\_contribution}}$ (Hybrid GRU-D $-$ Frozen-Control)",
    "Delta_temporal_alone": "$\\Delta_{\\text{temporal\\_alone}}$ (Temporal-Only $-$ XGBoost-Matched)",
    "Delta_static_only": "$\\Delta_{\\text{static\\_only}}$ (Static-Only $-$ Temporal-Only)",
    "Delta_modern_comparator": "$\\Delta_{\\text{modern\\_comparator}}$ (Hybrid GRU-D $-$ mTAN)",
}
DELTA_ORDER = ["Delta_representation", "Delta_static_contribution", "Delta_temporal_alone",
               "Delta_static_only", "Delta_modern_comparator"]


def table_deltas():
    with open(os.path.join(DATA_DIR, "m2_v2_deltas.json")) as f:
        deltas = json.load(f)
    lines = [
        "% Auto-generated by m2_generate_tables_v2.py from data/m2_v2_deltas.json -- do not hand-edit.",
        "% Patient-cluster bootstrap (N=10000/seed), mean of per-seed 95% CIs, Holm-corrected across the 5-delta family.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{The 5 v2 discrimination deltas (AUROC), patient-cluster bootstrap 95\\% CIs, "
        "Holm-corrected for multiplicity (Sec.24.2b). All values post-tuning-symmetry (Sec.24.2, "
        "Phase 2). Every delta is significant at $\\alpha=0.05$; $\\Delta_{\\text{temporal\\_alone}}$ "
        "is the reversal finding (Sec.24.2b item 2) -- tuned XGBoost significantly beats Temporal-Only "
        "GRU-D v2 alone.}",
        "\\label{tab:m2-v2-deltas}",
        "\\resizebox{\\textwidth}{!}{%",
        "\\begin{tabular}{lcccc}",
        "\\toprule",
        "Delta & Mean & SD (seeds) & Holm-corrected $p$ & Significant \\\\",
        "\\midrule",
    ]
    for name in DELTA_ORDER:
        d = deltas[name]
        sig = "Yes" if d["holm_significant_at_0.05"] else "No"
        p = d["holm_corrected_p"]
        p_str = "$<$0.001" if p < 0.0005 else f"{p:.4f}"
        lines.append(f"{DELTA_LABEL[name]} & {d['mean']:+.4f} & {d['sd']:.4f} & {p_str} & {sig} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}%", "}", "\\end{table}"]
    write(os.path.join(OUT_DIR, "deltas_v2.tex"), lines)


def table_conformal_summary():
    df = pd.read_csv(os.path.join(DATA_DIR, "m2_v2_conformal_summary.csv"))
    models = ["Temporal-Only GRU-D v2", "Frozen-Temporal Head Control v2", "Hybrid GRU-D v2"]
    lines = [
        "% Auto-generated by m2_generate_tables_v2.py from data/m2_v2_conformal_summary.csv -- do not hand-edit.",
        "% Mean over 5 confirmatory seeds, chronological-primary split, alpha=0.1 (90% target coverage).",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Marginal vs.\\ class-1 (deterioration) coverage, MAPIE (split-conformal) vs.\\ ECI "
        "(adaptive) vs.\\ Mondrian-LAC (label-conditional), chronological-primary split (Sec.24.3, this "
        "module's headline result). MAPIE and ECI achieve near-target MARGINAL coverage but collapse on "
        "the minority class; only Mondrian-LAC restores class-1 coverage near target.}",
        "\\label{tab:m2-v2-conformal}",
        "\\resizebox{\\textwidth}{!}{%",
        "\\begin{tabular}{lccc}",
        "\\toprule",
        "Model & MAPIE (marginal / class-1) & ECI (marginal / class-1) & Mondrian-LAC (class-1) \\\\",
        "\\midrule",
    ]
    for m in models:
        sub = df[df["model"] == m]
        mapie = f"{sub['mapie_coverage'].mean():.4f} / {sub['mapie_coverage_class1'].mean():.4f}"
        eci = f"{sub['eci_coverage'].mean():.4f} / {sub['eci_coverage_class1'].mean():.4f}"
        mondrian = f"{sub['mondrian_lac_coverage_class1'].mean():.4f} $\\pm$ {sub['mondrian_lac_coverage_class1'].std():.4f}"
        label = m.replace(" v2", "").replace("Frozen-Temporal Head Control", "Frozen-Temporal Head Control")
        if m == "Hybrid GRU-D v2":
            label = "\\textbf{Hybrid GRU-D (primary)}"
        lines.append(f"{label} & {mapie} & {eci} & {mondrian} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}%", "}", "\\end{table}"]
    write(os.path.join(OUT_DIR, "conformal_summary_v2.tex"), lines)


