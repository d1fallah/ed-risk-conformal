def table_news2_sensitivity():
    df = pd.read_csv(os.path.join(DATA_DIR, "m2_news2_sensitivity.csv"))
    lines = [
        "% Auto-generated by m2_generate_tables_v2.py from data/m2_news2_sensitivity.csv -- do not hand-edit.",
        "% Patient-cluster bootstrap 95% CIs.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{NEWS2 six-arm sensitivity analysis (Sec.23 row 3): the triage-scored composite "
        "(Arm A, as reported elsewhere in this module) undercounts published ED-validation AUROC "
        "(0.71-0.86) because it is scored at triage, the only point at which GRU-D's $t=0$ prediction "
        "is available. Arm F -- NEWS2 recomputed on the last-recorded ED vitals rather than "
        "triage-only -- lands inside the published range, isolating scoring timepoint as the "
        "explanation rather than outcome definition or missingness.}",
        "\\label{tab:m2-news2-sensitivity}",
        "\\begin{tabular}{lccc}",
        "\\toprule",
        "Arm & $n$ (positives) & AUROC & 95\\% CI \\\\",
        "\\midrule",
    ]
    for _, r in df.iterrows():
        n_pos = int(round(r["n"] * r["pos_rate"]))
        lines.append(f"{ARM_LABEL[r['arm']]} & {int(r['n'])} ({n_pos}) & {r['auroc']:.4f} & "
                      f"[{r['auroc_ci_lo']:.4f}, {r['auroc_ci_hi']:.4f}] \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    write(os.path.join(OUT_DIR, "news2_sensitivity.tex"), lines)


CMP_ORDER = ["A", "B", "C1", "C2", "D", "E"]
CMP_LABEL = {"A": "A: static Mondrian-LAC", "B": "B: Mondrian-ECI (online, label-cond.)",
             "C1": "C1: static Mondrian + recal.\\ ($W{=}10$k)", "C2": "C2: static Mondrian + recal.\\ ($W{=}40$k)",
             "D": "D: static score-bin Mondrian", "E": "E: online score-bin ECI"}


def _pm(x, digits=3):
    return f"{x.mean():.{digits}f} $\\pm$ {x.std():.{digits}f}"


def table_mondrian_comparators():
    df = pd.read_csv(os.path.join(DATA_DIR, "m2_v2_mondrian_eci_comparators.csv"))
    d = df[df["model"] == "Hybrid GRU-D v2"]
    lines = [
        "% Auto-generated by m2_generate_tables_v2.py from data/m2_v2_mondrian_eci_comparators.csv -- do not hand-edit.",
        "% Hybrid GRU-D v2, mean +/- std over 5 seeds, chronological-primary split. Pre-registered (M2_MondrianECI_PreRegistration.md Part 4).",
        "\\begin{table}[H]",
        "\\centering",
        "\\caption{Pre-registered decisive comparators for the online label-conditional construction (Sec.24.3b), Hybrid GRU-D v2. "
        "A method is \\emph{valid} if coverage of both classes is $\\geq 0.89$. Efficiency is compared only among valid methods. "
        "Static Mondrian with periodic recalibration (C1, C2) is valid with smaller sets than Mondrian-ECI (B): the online construction is not needed "
        "(verdict NOT NEEDED, identical on the other two models). Score-bin conditioning (D, E) fails the minority class (class-1 coverage 0.23--0.29), "
        "so conditioning on covariates of the model's own risk score does not replace conditioning on the true label. "
        "Labels assumed immediate for all methods; recalibration windows are in arrivals, not calendar time.}",
        "\\label{tab:m2-mondrian-comparators}",
        "\\resizebox{\\textwidth}{!}{%",
        "\\begin{tabular}{lccccc}",
        "\\toprule",
        "Method & Class-0 cov. & Class-1 cov. & Mean $|C|$ & Informative $P(C{=}\\{1\\}\\mid y{=}1)$ & Valid \\\\",
        "\\midrule",
    ]
    for m in CMP_ORDER:
        r = d[d["method"] == m]
        assert len(r) == 5, f"{m}: expected 5 seeds"
        valid = (r["coverage_class0"].mean() >= 0.89) and (r["coverage_class1"].mean() >= 0.89)
        lines.append(f"{CMP_LABEL[m]} & {_pm(r['coverage_class0'])} & {_pm(r['coverage_class1'])} & "
                      f"{_pm(r['mean_set_size'])} & {_pm(r['informative_class1'])} & {'yes' if valid else 'no'} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}%", "}", "\\end{table}"]
    write(os.path.join(OUT_DIR, "mondrian_comparators.tex"), lines)


