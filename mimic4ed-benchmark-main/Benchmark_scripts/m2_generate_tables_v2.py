def table_eci_vs_recal():
    df = pd.read_csv(os.path.join(DATA_DIR, "m2_v2_eci_vs_recalibration.csv"))
    lines = [
        "% Auto-generated by m2_generate_tables_v2.py from data/m2_v2_eci_vs_recalibration.csv -- do not hand-edit.",
        "% Mean +/- std over 5 seeds. Pre-registered (M2_ECI_vs_Recalibration_PreRegistration.md).",
        "\\begin{table}[H]",
        "\\centering",
        "\\caption{ECI versus periodic recalibration of ordinary split-conformal, marginal coverage and mean clipped interval width (Sec.24.3c). "
        "Valid means marginal coverage $\\geq 0.89$. On every model, recalibration is valid with narrower intervals than ECI (verdict: ECI NOT NEEDED, "
        "pre-registered). ECI is run exactly as the module always ran it. Labels assumed immediate for all methods.}",
        "\\label{tab:m2-eci-vs-recal}",
        "\\resizebox{\\textwidth}{!}{%",
        "\\begin{tabular}{l" + "cc" * len(ER_ORDER) + "}",
        "\\toprule",
        "Model & " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{ER_LABEL[m]}}}" for m in ER_ORDER) + " \\\\",
        "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}\\cmidrule(lr){8-9}",
        " & " + " & ".join("Cov. & Width" for _ in ER_ORDER) + " \\\\",
        "\\midrule",
    ]
    for key, label in ER_MODELS:
        cells = []
        for m in ER_ORDER:
            r = df[(df["model"] == key) & (df["method"] == m)]
            assert len(r) == 5, f"{key}/{m}: expected 5 seeds"
            cells += [_pm(r["coverage"], 4), _pm(r["width"], 3)]
        lines.append(f"{label} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}%", "}", "\\end{table}"]
    write(os.path.join(OUT_DIR, "eci_vs_recalibration.tex"), lines)



HZ_MODELS = [("Hybrid GRU-D v2", "Hybrid GRU-D"), ("Temporal-Only GRU-D v2", "Temporal-Only GRU-D"),
             ("XGBoost-Matched v2", "XGBoost-Matched")]
HZ_ROWS = [("1h", "1h$^{\\dagger}$"), ("6h", "6h"), ("12h", "12h")]


def table_horizon_ablation():
    summ = pd.read_csv(os.path.join(DATA_DIR, "m2_v2_horizon_summary.csv"))
    with open(os.path.join(DATA_DIR, "m2_v2_horizon_deltas.json")) as f:
        dj = json.load(f)
    lines = [
        "% Auto-generated by m2_generate_tables_v2.py from data/m2_v2_horizon_summary.csv and m2_v2_horizon_deltas.json -- do not hand-edit.",
        "% AUROC mean +/- std over 5 seeds; deltas are patient-cluster bootstrap 95% CIs (mean of per-seed CIs), Holm over the 6 confirmatory tests.",
        "\\begin{table}[H]",
        "\\centering",
        "\\caption{Horizon ablation (1h/6h/12h), real time-to-event labels $y_h$ (Gate v2 Sec.3), chronological-primary split (Sec.24.6). "
        "Per-horizon encoders; composite-outcome tuned hyperparameters at every horizon (not re-tuned); 3 of 6 models. "
        "``Sig.'' requires Holm-significance and all 5 seed CIs excluding zero. "
        "$^{\\dagger}$The 1h arm is underpowered (66 test positives, 14 validation positives) and must not be interpreted. "
        "The sign of the temporal-only effect depends on the horizon: Temporal-Only GRU-D beats tuned XGBoost at 6h, ties at 12h, and loses on the composite outcome (Sec.24.2b).}",
        "\\label{tab:m2-horizon}",
        "\\resizebox{\\textwidth}{!}{%",
        "\\begin{tabular}{lrccccc}",
        "\\toprule",
        "Horizon & Test pos. & Hybrid & Temporal-Only & XGBoost & Hybrid $-$ XGB (95\\% CI; sig.) & Temporal $-$ XGB (95\\% CI; sig.) \\\\",
        "\\midrule",
    ]
    for h, label in HZ_ROWS:
        cells = []
        for key, _ in HZ_MODELS:
            r = summ[(summ.horizon == h) & (summ.model == key)].iloc[0]
            cells.append(f"{r.auroc_mean:.4f} $\\pm$ {r.auroc_sd:.4f}")
        n_pos = int(summ[summ.horizon == h].n_pos.iloc[0])
        dcells = []
        for dn in ("D_repr", "D_temporal"):
            d = dj[h]["deltas"][dn]
            dcells.append(f"{d['mean']:+.4f} [{d['ci_lo_mean']:+.4f}, {d['ci_hi_mean']:+.4f}]; "
                          f"{'yes' if d['called_significant'] else 'no'}")
        lines.append(f"{label} & {n_pos:,} & " + " & ".join(cells) + " & " + " & ".join(dcells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}%", "}", "\\end{table}"]
    write(os.path.join(OUT_DIR, "horizon_ablation.tex"), lines)


