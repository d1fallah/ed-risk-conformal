"""Builds results/revision_v2/phase2/PHASE2_REPORT.md from the stored Phase 2 JSON files (every number is read, none typed)."""
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import rv2_common as C  # noqa: E402

P2 = os.path.join(C.RES, "phase2")
J = lambda n: json.load(open(os.path.join(P2, n)))  # noqa: E731
f3 = lambda x: f"{x:.3f}"  # noqa: E731
f4 = lambda x: f"{x:.4f}"  # noqa: E731
pc = lambda x: f"{100 * x:.1f}%"  # noqa: E731


def tbl(h, rows):
    return "\n".join(["| " + " | ".join(h) + " |", "|" + "|".join("---" for _ in h) + "|"] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


def main():
    co, ct, cf, nw, ca, sw = J("p2_1_cohorts.json"), J("p2_4_contrasts.json"), J("p2_5_conformal.json"), J("p2_6_news2.json"), J("p2_7_calibration_subgroups.json"), J("p2_10_landmark_sweep.json")
    cl = J("p2_2_classical.json")
    L = ["# Phase 2 report (landmark retraining; R2, R5 to R7)", "",
         "Generated by `src/revision_v2/phase2/p2_report.py` from stored JSON; the manuscript tables come from the same files through the provenance accessor.",
         "Decisions taken while the user was away (all logged in `../DEVIATIONS.md`): Phase 1 review point passed; the Elixhauser count kept (R1 not triggered) with a feature-builder correction for 42 stays; four configurations per tuned model.",
         "Tuning budget fixed in `TUNING_BUDGET.md` before any run. Bootstrap: patient-cluster, 10,000 resamples for the primary AUROC and contrasts, 1,000 for AUPRC, the secondary outcome and subgroup intervals. Seed variability (SD over five seeds) and bootstrap intervals are separate (rule 10).", ""]
    rows = []
    for lm, name in (("triage", "Arrival landmark"), ("h2", "2 h landmark")):
        for r, rn in (("fit", "training"), ("val", "validation"), ("cs", "calibration selection"), ("fc", "final calibration"), ("test", "test")):
            b = co["landmarks"][lm]["splits"][r]
            rows.append([name, rn, f"{b['stays_in_split']:,}", f"{b['eligible_stays']:,}", f"{b['primary_positives']:,}", pc(b["primary_prevalence"]), f"{b['secondary_positives']:,}", pc(b["secondary_prevalence"])])
    L += ["## 2.1 Cohorts", "", tbl(["Landmark", "Subset", "Stays", "Eligible", "Primary events", "Rate", "Secondary events", "Rate"], rows), "",
          f"2 h sequence slots: {co['h2_sequence_rows_within_2h']['T_ED_chosen']} ED rows (covers 99.5% of eligible stays; {co['h2_sequence_rows_within_2h']['stays_truncated']:,} stays truncated). "
          f"Eligible stays with no ED vital sign by 2 h: training period {pc(co['h2_tensors']['train_v2']['stays_with_zero_ed_rows'] / co['h2_tensors']['train_v2']['rows'])}, test {pc(co['h2_tensors']['test_v2']['stays_with_zero_ed_rows'] / co['h2_tensors']['test_v2']['rows'])}.", ""]
    rows = []
    for lm, name in (("h2", "2 h"), ("triage", "arrival")):
        for k, m in ct["landmarks"][lm]["models"].items():
            sec = ct["landmarks"][lm]["secondary_outcome"]["models"][k]
            rows.append([name, k, f"{f4(m['auroc_seed_mean'])} (SD {f4(m['auroc_seed_sd'])})", f"[{f4(m['auroc_bootstrap_ci95_of_seed_mean'][0])}, {f4(m['auroc_bootstrap_ci95_of_seed_mean'][1])}]",
                         f4(m["auprc_seed_mean"]), f4(sec["auroc_seed_mean"])])
        n = nw["landmarks"][lm]
        rows.append([name, "NEWS2 (5 parameters)", f4(n["auroc"]), f"[{f4(n['auroc_ci95'][0])}, {f4(n['auroc_ci95'][1])}]", "", ""])
    L += ["## 2.2 and 2.3 Discrimination (primary outcome, test period)", "", tbl(["Landmark", "Model", "AUROC (seed mean, SD)", "Bootstrap 95% CI of seed mean", "AUPRC", "Secondary AUROC"], rows), ""]
    rows = []
    for cid in ("C1", "C2", "C3", "C4", "C5"):
        lm = "triage" if cid == "C5" else "h2"
        c = ct["landmarks"][lm]["contrasts"][cid]
        rows.append([cid, f"{c['a']} - {c['b']}", f"{c['delta_seed_mean']:+.4f} (SD {c['delta_seed_sd']:.4f})", f"[{c['delta_bootstrap_ci95_of_seed_mean'][0]:+.4f}, {c['delta_bootstrap_ci95_of_seed_mean'][1]:+.4f}]",
                     f"{c['holm_adjusted_p']:.4f}", "yes" if c["all_seed_cis_exclude_zero"] else "no", "yes" if c["significant"] else "no"])
    L += ["### R7 contrasts", "", tbl(["ID", "Contrast", "Difference", "Bootstrap 95% CI", "Holm p", "All 5 per-seed CIs exclude 0", "Significant"], rows), "",
          "The Holm values are at the floor of what 10,000 resamples resolve. The primary model (Hybrid-E2E, R6) is slightly below the timing-aware trees; the recurrent model does not beat the simpler baselines by a margin that matters.", ""]
    rows = []
    for h in ("0", "1", "2", "3", "4", "6"):
        d = sw["landmarks"][h]
        rows.append([h, f4(d["logreg"]), f4(d["trees"])])
    L += ["## Landmark-time sensitivity (logistic regression and trees)", "", tbl(["Landmark (h)", "Logistic regression AUROC", "Trees AUROC"], rows), ""]
    r0 = cf["runs"]
    mean = lambda f: float(np.mean([f(r) for r in r0]))  # noqa: E731
    rows = []
    for k, n in (("static_lac", "Static LAC"), ("eci_sets", "ECI sets"), ("static_mondrian_lac", "Static Mondrian-LAC"), ("mondrian_eci", "Mondrian-ECI"), ("mondrian_recal_w10k", "Mondrian recalibration W=10k")):
        g = lambda r, k=k: r["sweep"]["0.1"][k]  # noqa: E731
        rows.append([n, f3(mean(lambda r: g(r)["metrics"]["coverage_marginal"])), f3(mean(lambda r: g(r)["metrics"]["coverage_class1"])), f3(mean(lambda r: g(r)["metrics"]["mean_set_size"])),
                     f3(mean(lambda r: g(r)["operating"]["ppv_only1"])), f3(mean(lambda r: g(r)["operating"]["sensitivity_only1"])), f"{mean(lambda r: g(r)['operating']['false_alarms_per_100_patients']):.1f}"])
    L += ["## 2.4 Conformal suite on the primary model (alpha = 0.10, mean of 5 seeds)", "", tbl(["Method", "Coverage", "Class-1 coverage", "Set size", "PPV of {1}", "Sensitivity of {1}", "False alarms / 100"], rows), "",
          "Score intervals: " + "; ".join(f"{k} coverage {f3(mean(lambda r, k=k: r['intervals'][k]['coverage']))} width {f3(mean(lambda r, k=k: r['intervals'][k]['width']))}" for k in ("static", "eci", "recal_w10k", "recal_w40k")) + ".", "",
          "Full alpha sweep, label-delay and drift tables, stream-order permutations, score distributions, calibration and subgroups: `p2_5_conformal.json`, `p2_8_stream_order.json`, `p2_9_score_distribution.json`, `p2_7_calibration_subgroups.json`.", ""]
    L += ["## Stop point", "", "Phase 2 ends here. The manuscript is `module2/paper-m2-rev/`; the reviewer-loop scores are in its `reviews/` folder.", ""]
    open(os.path.join(P2, "PHASE2_REPORT.md"), "w", encoding="utf-8").write("\n".join(L))
    print("written")


if __name__ == "__main__":
    main()
