"""Builds results/revision_v2/phase1/PHASE1_REPORT.md from the stored Phase 1 JSON files (every number is read, none typed)."""
import json
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import rv2_common as C  # noqa: E402

P1 = os.path.join(C.RES, "phase1")
P0 = os.path.join(C.RES, "phase0")
J = lambda d, n: json.load(open(os.path.join(d, n)))  # noqa: E731
f4 = lambda x: f"{x:.4f}"  # noqa: E731
pc = lambda x: f"{100 * x:.1f}%"  # noqa: E731
ci = lambda c: f"[{c[0]:.4f}, {c[1]:.4f}]"  # noqa: E731
MODELS3 = ["Temporal-Only GRU-D v2", "Frozen-Temporal Head Control v2", "Hybrid GRU-D v2"]


def md_table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main():
    cc = J(P0, "p05_cohort_counts.json")
    sh = J(P1, "p1_2_shortcuts.json")
    el = J(P1, "p1_3_elixhauser_ablation.json")
    du = J(P1, "p1_4_duration_strata.json")
    sc = J(P1, "p1_5_score_distributions.json")
    op = J(P1, "p1_6_7_operating_and_alpha.json")
    so = J(P1, "p1_8_stream_order.json")
    L = []
    L += ["# Phase 1 report (diagnostics on the existing models; no encoder retraining)", "",
          "Generated by `src/revision_v2/phase1/p1_report.py` from the stored JSON outputs of `p1_2` to `p1_8` (and `phase0/p05_cohort_counts.json`); every number is read, none typed.",
          "Bootstrap: patient-cluster (patients resampled with all their stays), 1,000 resamples for these diagnostics (rule 5, Phase 1), 95% percentile intervals, paired draws for contrasts.",
          "Seed variability (mean +- SD over the five training seeds) and bootstrap uncertainty (sampling) are reported separately (rule 10). Test-period data were used only for evaluation; nothing here selects or tunes.",
          "Primary target: `outcome_critical` (in-hospital death or ICU transfer within 12 h of ED departure) on the end-of-stay task as originally built.", ""]
    # 1.1
    rows = []
    for name, d in (("training (development)", cc["dev_subsets"]["training"]), ("validation", cc["dev_subsets"]["validation"]),
                    ("calibration_selection", cc["dev_subsets"]["calibration_selection"]),
                    ("final_conformal_calibration", cc["dev_subsets"]["final_conformal_calibration"]), ("test period", cc["test_period"]),
                    ("excluded returning-patient stays", cc["excluded_returning_patient_stays"])):
        rows.append([name, f"{d['stays']:,}", f"{d['patients']:,}", f"{d['positives_outcome_critical']:,}", pc(d["prevalence_outcome_critical"])])
    L += ["## 1.1 Prevalence", "", md_table(["Subset", "Stays", "Patients", "Positives", "P(Y = 1)"], rows), "",
          f"Prevalence rises from {pc(cc['train_period']['prevalence_outcome_critical'])} over the whole training period to {pc(cc['test_period']['prevalence_outcome_critical'])} in the test period; "
          f"the final-calibration subset ({pc(cc['dev_subsets']['final_conformal_calibration']['prevalence_outcome_critical'])}) sits between them. "
          f"Time-anchored labels: the 1 h label has {cc['test_period']['positives_y_1h']} test positives, {cc['dev_subsets']['calibration_selection']['positives_y_1h']} in calibration_selection and "
          f"{cc['dev_subsets']['final_conformal_calibration']['positives_y_1h']} in final calibration.", ""]
    # 1.2
    rows = []
    for k, label in (("A_only", "Group A only (ED duration, sequence length, per-vital counts)"), ("B_only", "Group B only (triage-time missingness)"),
                     ("A_plus_B", "Groups A + B"), ("duration_alone", "ED duration alone")):
        b = sh["baselines"][k]
        rows.append([label, f4(b["test_auroc"]), ci(b["test_auroc_ci95"]), f4(b["test_auprc"]), ci(b["test_auprc_ci95"])])
    mrows = []
    for m, v in sh["models"].items():
        mrows.append([m, f"{v['auroc_seed_summary']['mean']:.4f} +- {v['auroc_seed_summary']['sd']:.4f}",
                      "; ".join(f"{s}: {ci(c)}" for s, c in v["per_seed_bootstrap_ci95_auroc"].items())[:130] + " ...", f4(v["auprc_seed_summary"]["mean"])])
    A, AB = sh["baselines"]["A_only"], sh["baselines"]["A_plus_B"]
    L += ["## 1.2 Shortcut baselines (a leakage diagnostic, not candidate models)", "",
          "Logistic regression on the development `training` subset, regularisation tuned on `validation`, evaluated once on the test period "
          f"({sh['n_test']:,} stays, {sh['n_test_positive']:,} positives).", "",
          md_table(["Features", "Test AUROC", "95% CI (patient-cluster bootstrap)", "Test AUPRC", "95% CI"], rows), "",
          "Stored models for reference (test AUROC, mean +- SD over five seeds; bootstrap CIs per seed shown in part):", "",
          md_table(["Model", "AUROC (seed mean +- SD)", "Per-seed bootstrap 95% CIs", "AUPRC (seed mean)"], mrows), "",
          f"**Finding.** Quantities that describe how long and how intensively the patient was monitored (group A) reach an AUROC of {f4(A['test_auroc'])} {ci(A['test_auroc_ci95'])}, and "
          f"with triage-time missingness (A + B) {f4(AB['test_auroc'])} {ci(AB['test_auroc_ci95'])}, against {f4(sh['models']['Hybrid GRU-D v2']['auroc_seed_summary']['mean'])} for Hybrid GRU-D. "
          "ED duration alone is weak "
          f"({f4(sh['baselines']['duration_alone']['test_auroc'])}), so the workflow signal sits in the measurement counts and the missingness pattern. High discrimination from group A is itself a "
          "finding that motivates the landmark redesign of Phase 2 (R2, R5 to R7); it does not show that the physiological signal is absent.", ""]
    # 1.3
    h = el["hybrid"]
    rows = [[s, f4(h[str(s)]["auroc_with"]), f4(h[str(s)]["auroc_without"]), f"{h[str(s)]['delta_auroc']:+.4f}", ci(h[str(s)]["delta_auroc_ci95"])] for s in C.SEEDS]
    x = el["xgboost"]
    hs = el["hybrid_seed_summary"]
    L += ["## 1.3 Elixhauser ablation", "",
          "Phase 0 found the count valid by design (AUDIT_REPORT.md 0.2), so this is the planned sensitivity analysis. The Hybrid static branch and head were retrained without "
          "`comorbidity_elixhauser_count` on the same frozen encoders (5 seeds, tuned head configuration of the original), and XGBoost-Matched without the column (38 features).", "",
          md_table(["Seed", "AUROC with count", "AUROC without", "Delta (without - with)", "Paired bootstrap 95% CI of delta"], rows), "",
          f"Hybrid: delta AUROC mean {hs['delta_auroc']['mean']:+.4f} (SD {hs['delta_auroc']['sd']:.4f} over seeds); every per-seed interval excludes zero but the effect is below 0.001. "
          f"XGBoost-Matched: {f4(x['auroc_with'])} with, {f4(x['auroc_without'])} without, delta {x['delta_auroc']:+.4f} {ci(x['delta_auroc_ci95'])}. "
          "The count carries a statistically detectable but practically negligible share of the discrimination; removing it would not change any conclusion.", ""]
    # 1.4
    rows = []
    for m, v in du["models"].items():
        rows.append([m, f4(v["overall_auroc"]["mean"])] + [f"{v['quartiles'][str(k)]['mean']:.4f} {ci(v['quartiles'][str(k)]['bootstrap_ci95_of_seed_mean'])}" for k in range(1, 5)])
    cuts = du["cut_points_hours_training_period"]
    L += ["## 1.4 Duration-stratified discrimination", "",
          f"ED-duration quartile cut points from the training period ({du['n_training_period']:,} stays): {cuts[0]:.2f} h, {cuts[1]:.2f} h, {cuts[2]:.2f} h. Test quartiles: n = "
          + ", ".join(f"{n:,}" for n in du["test_quartile_n"]) + "; prevalence " + ", ".join(pc(p) for p in du["test_quartile_prevalence"]) + "; positives "
          + ", ".join(f"{n:,}" for n in du["test_quartile_positives"]) + ".", "",
          md_table(["Model", "Overall AUROC", "Q1 (shortest)", "Q2", "Q3", "Q4 (longest)"], rows), "",
          "Within-quartile values are seed means with the patient-cluster bootstrap 95% CI of the seed-averaged AUROC. Discrimination stays high inside every quartile for the GRU-D family and XGBoost, "
          "so duration alone does not account for it, and it falls steadily with duration (Hybrid GRU-D "
          f"{f4(du['models']['Hybrid GRU-D v2']['quartiles']['1']['mean'])} in the shortest quartile to {f4(du['models']['Hybrid GRU-D v2']['quartiles']['4']['mean'])} in the longest). "
          "Prevalence falls with duration, from the shortest to the longest quartile.", ""]
    # 1.5
    rows = []
    for m in MODELS3:
        r = sc["models"][m]["42"]
        rows.append([m, f"{r['final_calibration']['p_given_y0_q']['0.9']:.4f} / {r['test']['p_given_y0_q']['0.9']:.4f}",
                     f"{r['final_calibration']['p_given_y1_q']['0.5']:.4f} / {r['test']['p_given_y1_q']['0.5']:.4f}",
                     f"{r['static_qhat_marginal']:.4f} / {r['test_empirical_0.9_quantile_lac']:.4f}",
                     f"{r['static_qhat_class1']:.4f} / {r['test_empirical_0.9_quantile_lac_class1']:.4f}",
                     f"{r['static_qhat_class0']:.4f} / {r['test_empirical_0.9_quantile_lac_class0']:.4f}"])
    L += ["## 1.5 Score distributions, final calibration vs test (seed 42; other seeds in the JSON)", "",
          md_table(["Model", "p_hat|y=0, q0.9 (cal / test)", "p_hat|y=1, median (cal / test)", "Marginal LAC: static q_hat / test empirical 0.9 quantile",
                    "Class-1: static q_hat / test 0.9 quantile", "Class-0: static q_hat / test 0.9 quantile"], rows), "",
          "Quantiles 0.5, 0.9, 0.95 of p_hat|y=0, p_hat|y=1 and the LAC score, and 101-point ECDFs, are in `p1_5_score_distributions.json` for all five seeds. The static marginal q_hat is "
          "close to the test-period empirical 0.9 quantile of the LAC score for all three models, which is why static coverage held; the class-0 test scores are slightly lower than in calibration "
          "(fewer high scores among non-events) and the class-1 test scores slightly higher. Descriptive only; no p-value.", ""]
    # 1.6
    runs = pd.DataFrame([{"model": r["model"], "seed": r["seed"], "alpha": r["alpha"], "method": r["method"], **r["metrics"], **{k: v for k, v in r["operating"].items() if not isinstance(v, dict)},
                          "feasible": r["class1_quantile_feasible"]} for r in op["runs"]])
    h10 = runs[(runs.model == "Hybrid GRU-D v2") & (np.isclose(runs.alpha, 0.10))].groupby("method").mean(numeric_only=True)
    names = {"static_lac": "Static LAC (marginal)", "static_mondrian_lac": "Static Mondrian-LAC", "eci_sets": "ECI sets (marginal)", "mondrian_eci": "Mondrian-ECI"}
    rows = [[names[m], f4(h10.loc[m, "coverage_marginal"]), f4(h10.loc[m, "coverage_class1"]), f4(h10.loc[m, "mean_set_size"]), pc(h10.loc[m, "rate_singleton_1"]), pc(h10.loc[m, "rate_singleton_0"]),
             pc(h10.loc[m, "rate_both"]), pc(h10.loc[m, "rate_empty"]), f4(h10.loc[m, "ppv_only1"]), f4(h10.loc[m, "sensitivity_only1"]), f4(h10.loc[m, "fpr_only1"]),
             f"{h10.loc[m, 'false_alarms_per_100_patients']:.2f}", pc(h10.loc[m, "abstain_any_class0"]), pc(h10.loc[m, "abstain_any_class1"])] for m in names]
    L += ["## 1.6 Clinical operating characteristics and prediction-set efficiency (alpha = 0.10, Hybrid GRU-D, mean of five seeds)", "",
          "No cost or utility function is used. `{1}` = singleton set containing label 1; abstention = set with both labels or empty.", "",
          md_table(["Method", "Marg. cov.", "Class-1 cov.", "Mean set size", "{1}", "{0}", "{0,1}", "empty", "PPV of {1}", "Sens. of {1}", "FPR of {1}", "False alarms /100", "Abstain, class 0", "Abstain, class 1"], rows), "",
          "The full set-type x true-class cross-tables for every model, seed and alpha are in `p1_6_7_operating_and_alpha.json` (`operating.cross`). "
          "Marginal sets are almost never `{1}` and cover about a fifth of the positives; the class-conditional sets restore class-1 coverage but the `{1}` set then has a positive predictive value of "
          f"{f4(h10.loc['static_mondrian_lac', 'ppv_only1'])} (static) and {f4(h10.loc['mondrian_eci', 'ppv_only1'])} (Mondrian-ECI), at "
          f"{h10.loc['static_mondrian_lac', 'false_alarms_per_100_patients']:.1f} and {h10.loc['mondrian_eci', 'false_alarms_per_100_patients']:.1f} false alarms per 100 patients: "
          "this is the false-alarm burden the original paper did not report.", ""]
    # 1.7
    rows = []
    for a in (0.20, 0.10, 0.05, 0.01):
        for m in names:
            g = runs[(runs.model == "Hybrid GRU-D v2") & np.isclose(runs.alpha, a) & (runs.method == m)]
            rows.append([f"{a:.2f}", names[m], f"{g.coverage_marginal.mean():.4f} +- {g.coverage_marginal.std():.4f}", f"{g.coverage_class0.mean():.4f}", f"{g.coverage_class1.mean():.4f} +- {g.coverage_class1.std():.4f}",
                         f4(g.mean_set_size.mean()), pc(g.rate_singleton_1.mean()), pc(g.rate_both.mean()), pc(g.rate_empty.mean()), str(op["runs"][0]["class1_calibration_positives"])
                         + (" (feasible)" if bool(g.feasible.all()) else " (NOT feasible)")])
    L += ["## 1.7 Alpha sweep (Hybrid GRU-D; mean +- SD over five seeds; eta re-selected per alpha on calibration_selection only)", "",
          md_table(["alpha", "Method", "Marginal cov.", "Class-0 cov.", "Class-1 cov.", "Mean set size", "{1}", "{0,1}", "empty", "Calibration positives behind class-1 quantile"], rows), "",
          "At alpha = 0.01 the class-1 quantile is computed from the 888 final-calibration positives (feasible: ceil((n+1)(1-alpha)) <= n); every alpha is feasible. The same table for the two other models is in the JSON. "
          "The marginal methods keep marginal coverage at every alpha and class-1 coverage stays far below it until alpha = 0.01, where the sets become large (set size > 1.18 on average).", ""]
    # 1.8
    runs8 = so["runs"]
    rows = []
    for m in MODELS3:
        for key, label in (("eci_interval", "ECI interval"), ("recal_w10k", "Recalibration W = 10k"), ("eci_set", "ECI set")):
            covs = [runs8[f"{m}|{s}"][key]["cov"] for s in C.SEEDS]
            wk = "width" if key != "eci_set" else "size"
            wd = [runs8[f"{m}|{s}"][key][wk] for s in C.SEEDS]
            rows.append([m, label, f"{np.mean([c['mean'] for c in covs]):.4f}", f"{min(c['min'] for c in covs):.4f}", f"{max(c['max'] for c in covs):.4f}",
                         f"{np.mean([w['mean'] for w in wd]):.4f}", f"{min(w['min'] for w in wd):.4f}", f"{max(w['max'] for w in wd):.4f}"])
    valid = {k: sum(v["valid_all_perms"][k] for v in runs8.values()) for k in ("eci_interval", "recal_w10k", "eci_set")}
    L += ["## 1.8 Stream-order robustness (20 permutations within each year block of the test stream, per seed)", "",
          md_table(["Model", "Method", "Mean cov.", "Min cov.", "Max cov.", "Mean width / size", "Min", "Max"], rows), "",
          f"Validity (marginal coverage >= 0.89) held in every permutation in {valid['eci_interval']} of {len(runs8)} model-seed runs for the ECI interval, {valid['recal_w10k']} for recalibration W = 10k and "
          f"{valid['eci_set']} for the ECI set. ECI intervals were narrower than recalibration in "
          f"{sum(v['eci_narrower_than_recal_all_perms'] for v in runs8.values())} of {len(runs8)} runs under all permutations and in "
          f"{sum(v['eci_narrower_than_recal_original'] for v in runs8.values())} under the original order, so the ordering reported in the paper (ECI not narrower than static or recalibrated) did not change. "
          "A robustness diagnostic only: real within-year order is unknown, and the permutations do not characterise stream-order effects beyond this.", ""]
    L += ["## Conclusions carried to Phase 2", "",
          "1. The end-of-stay task is exposed to a workflow shortcut (1.2, 1.4): inputs that describe how often and how long the patient was monitored predict the outcome well. The landmark redesign (R2, R5 to R7) is required.",
          "2. The Elixhauser count is not a source of leakage that matters (1.3).",
          "3. Conformal findings are stable to stream order (1.8) and to the level alpha for the marginal methods (1.7), and the clinical cost of class-conditional sets is now measurable (1.6): a {1} set has a PPV below 0.5 at alpha = 0.10.",
          "4. Phase 2 re-runs the whole conformal suite on the 2 h landmark model with the same code (checked to reproduce the stored alpha = 0.10 results exactly: maximum difference 2e-16).", ""]
    with open(os.path.join(P1, "PHASE1_REPORT.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(L))
    print("written", os.path.join(P1, "PHASE1_REPORT.md"))


if __name__ == "__main__":
    main()
