"""
M2 -- Evidence freeze, mirroring module 1's src/freeze_evidence.py (same purpose, leaner
implementation since M2 has no templated freeze-doc convention to fill in yet).

Generates, in one pass:
  - results/m2_evidence_manifest.json  -- SHA-256 of every data/*.csv and data/*.json artifact any
    generator script can cite, plus every src/*.py, git HEAD, tree-clean status, and the local
    venv's installed packages.
  - M2_FINAL_EVIDENCE_FREEZE.md         -- a self-contained status document (not templated from a
    separate file, unlike M1's docs/freeze_template.md -- M2 has no such template yet and writing
    one for a single generated document would be pure ceremony).

Amendment discipline (mirrors M1's): if results/m2_evidence_manifest.json already exists and ANY
data/*.{csv,json} hash would change, this script REFUSES to overwrite it unless run with
--amend "<date> <reason>". A src/*.py (tooling) hash change is applied silently -- expected during
paper-prep work, not a scientific-evidence change.

Usage:
    python freeze_evidence.py
    python freeze_evidence.py --amend "2026-09-22 rebuilt tables through the Evidence pipeline"
"""
from __future__ import annotations

import argparse
import fnmatch
import glob
import hashlib
import json
import os
import subprocess
import sys
from datetime import datetime, timezone

_HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(_HERE, "..")  # mimic4ed-benchmark-main/
sys.path.insert(0, _HERE)
from paper_data import SUPERSEDED_ARTIFACTS  # noqa: E402

MANIFEST_PATH = os.path.join(ROOT, "results", "m2_evidence_manifest.json")
FREEZE_MD_PATH = os.path.join(ROOT, "M2_FINAL_EVIDENCE_FREEZE.md")

# The M2 working tree uses one local Windows-native venv (mimic4ed-benchmark-main/.venv), unlike
# M1's three isolated WSL venvs -- confirmed by inspection (Scripts/, not bin/: a Windows venv).
VENV_PYTHON = os.path.join(ROOT, ".venv", "Scripts", "python.exe")

# `protected=True` marks SCIENTIFIC EVIDENCE (the CSV/JSON result artifacts every table sources):
# a hash change here is refused without --amend. `protected=False` marks tooling (src/*.py) --
# expected to keep changing during paper-prep work.
MANIFEST_GLOBS = [
    ("data/*.csv", True),
    ("data/*.json", True),
    ("src/*.py", False),
]
PROTECTED_GLOBS = {pattern for pattern, protected in MANIFEST_GLOBS if protected}


def sha256_file(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        h.update(f.read())
    return h.hexdigest()


def git(*args: str) -> str:
    try:
        return subprocess.check_output(["git", "-C", ROOT, *args], text=True).strip()
    except Exception:
        return "unavailable"


def collect_manifest_files() -> dict[str, str]:
    self_path = os.path.relpath(MANIFEST_PATH, ROOT).replace(os.sep, "/")
    out: dict[str, str] = {}
    for pattern, _protected in MANIFEST_GLOBS:
        for path in sorted(glob.glob(os.path.join(ROOT, pattern))):
            rel = os.path.relpath(path, ROOT).replace(os.sep, "/")
            if rel == self_path:
                continue
            out[rel] = sha256_file(path)
    return out


def pip_freeze(venv_python: str) -> list[str] | None:
    if not os.path.exists(venv_python):
        return None
    try:
        out = subprocess.check_output([venv_python, "-m", "pip", "list", "--format=freeze"], text=True)
        return sorted(out.strip().splitlines())
    except Exception as exc:  # pragma: no cover - environment-dependent
        return [f"# pip freeze failed: {exc}"]


def render_freeze_doc(manifest: dict) -> None:
    superseded = "\n".join(f"- `{name}` -- {reason}" for name, reason in sorted(SUPERSEDED_ARTIFACTS.items())) or "None yet."
    amendments = manifest.get("amendments", [])
    amend_text = "\n".join(f"- **{a['date_and_reason']}**: {', '.join(a['changed_files'])}" for a in amendments) if amendments else "None yet."
    venv_status = (f"{len(manifest['venv_packages'])} packages"
                   if manifest["venv_packages"] is not None else "NOT FOUND at freeze time")

    text = f"""# M2 Evidence Freeze

Generated by `src/freeze_evidence.py` -- never hand-edit; `src/verify_paper_assets.py` re-checks
every hash this document certifies.

- **Frozen:** {manifest['frozen_at_utc']}
- **Evidence commit (git HEAD at freeze time):** `{manifest['git_head']}`
- **Working tree clean for evidence paths (`data/`, `src/`):** {manifest['git_working_tree_clean']}
- **Manifest:** `results/m2_evidence_manifest.json` ({len(manifest['files'])} files hashed)
- **Venv:** `.venv` (Windows-native): {venv_status}

## Traceability pipeline

Every number in a generated table/figure/macro is read from a `data/*.csv` or `data/*.json`
artifact through `src/paper_data.py`'s `Evidence` class (never hand-typed), recorded in a
per-asset provenance sidecar under `paper_assets/provenance/`, and independently re-verified by
`src/verify_paper_assets.py` before the manuscript is allowed to cite it.

```
python src/generate_latex_tables.py     # (re)build every table from real artifacts
python src/generate_paper_macros.py     # (re)build \\MTwo... prose macros
python src/verify_paper_assets.py       # independent re-verification gate -- must exit 0
python src/freeze_evidence.py           # re-freeze after any evidence change
```

## Superseded artifacts (never cited by a paper asset)

{superseded}

## Amendments

{amend_text}
"""
    with open(FREEZE_MD_PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--amend", default=None, help='"<date> <reason>" -- required if a protected hash changed since the last freeze')
    args = parser.parse_args()

    files = collect_manifest_files()
    venv_packages = pip_freeze(VENV_PYTHON)

    def is_protected(rel_path: str) -> bool:
        return any(fnmatch.fnmatch(rel_path, pattern) for pattern in PROTECTED_GLOBS)

    prior_amendments = []
    if os.path.exists(MANIFEST_PATH):
        with open(MANIFEST_PATH, "r", encoding="utf-8") as f:
            prior = json.load(f)
        prior_amendments = prior.get("amendments", [])
        changed = {p for p in files if prior.get("files", {}).get(p) != files[p]}
        changed |= {p for p in prior.get("files", {}) if p not in files}
        protected_changed = {p for p in changed if is_protected(p)}
        if protected_changed and not args.amend:
            print("REFUSING to overwrite the evidence freeze: the following SCIENTIFIC EVIDENCE "
                  "artifacts changed hash", file=sys.stderr)
            for p in sorted(protected_changed):
                print(f"  {p}", file=sys.stderr)
            print('Re-run with --amend "<date> <reason>" if this is an intentional, dated amendment.', file=sys.stderr)
            return 1
        if protected_changed and args.amend:
            prior_amendments = prior_amendments + [{"date_and_reason": args.amend, "changed_files": sorted(protected_changed)}]

    manifest = {
        "frozen_at_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "git_head": git("rev-parse", "--short", "HEAD"),
        "git_working_tree_clean": git("status", "--short", "--", "data", "src") == "",
        "files": files,
        "venv_packages": venv_packages,
        "superseded_artifacts": SUPERSEDED_ARTIFACTS,
        "amendments": prior_amendments,
    }

    os.makedirs(os.path.dirname(MANIFEST_PATH), exist_ok=True)
    with open(MANIFEST_PATH, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2)

    render_freeze_doc(manifest)

    print(f"manifest: {len(files)} files hashed -> {MANIFEST_PATH}")
    print(f"freeze doc -> {FREEZE_MD_PATH}")
    if manifest["amendments"]:
        print(f"{len(manifest['amendments'])} amendment(s) recorded")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
