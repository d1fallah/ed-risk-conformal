"""
M2 -- Provenance sidecars for the figure PDFs (Phase 0 item 6 of the manuscript plan). Originally
11 pre-existing figures; a 12th (fig6_eci_vs_recalibration_v2) was added in Phase 2 to fill the gap
venue_style_notes.md Sec D flagged (backbone item 4 had a table, T6, but no paired figure).

Scope, deliberately narrower than src/generate_latex_tables.py's per-cell tracing: a figure is a
visual aggregate, not a set of discrete asserted numbers, so this does NOT re-implement each plot's
binning/aggregation logic through Evidence (e.g. fig2_calibration_v2's 10-bin reliability curve) --
that would duplicate Benchmark_scripts/m2_generate_report_figures*.py's own logic for no added
traceability, since the figure scripts already read only committed data/*.csv|json (Golden Rule
already satisfied at that level; confirmed by re-running both scripts against current data with no
errors before this sidecar pass was written -- see the generation log in this session).

What this DOES do, per figure:
  - Record which script generates it and which data/*.csv|json artifact(s) it reads (literal(),
    reason = script path) -- always.
  - Where the figure's headline visual claim is a single per-model scalar ALSO asserted by an
    existing table (fig1/fig3/fig4/fig5 v2, and their T=2/pre-fix counterparts fig1/fig3/fig4),
    source that same value through Evidence.get_csv()/reduce_csv() -- this both traces the number
    and lets verify_paper_assets.py's cross-asset-agreement check independently confirm the figure
    and its sibling table agree (they read the same artifact/column, so they must).
  - Purely diagnostic multi-panel figures with no single-scalar headline claim (fig2_calibration_v2,
    fig2_missingness_bug_training_curves, fig6_subgroup_interaction) get the script+artifact literal
    record only -- a reader can reproduce them exactly from the named script and artifact, which is
    the traceability this sidecar exists to establish.

Currency (2026-09-20 reframing): the T=2/pre-fix figures (fig1_headline_auroc,
fig2_missingness_bug_training_curves, fig3_calibration_ece, fig4_conformal, fig5_deltas_forest,
fig6_subgroup_interaction -- generated by Benchmark_scripts/m2_generate_report_figures.py, NOT the
_v2 script) are NOT stale duplicates of the v2 figures: they document the earlier T=2 cohort and the
missingness-bug pre-fix/post-fix narrative (M2_Hybrid_Deviation_Log.md), a different, still-valid
historical result. They are internal-only: the manuscript itself no longer carries any T=2
comparison, removed 2026-09-22 on supervisor review because that pipeline differed from the current
one in BOTH representation and split, making any difference unattributable to either change alone.
Both scripts were re-run against current data/ in this session with no errors, confirming
neither figure set is orphaned. ablation1_mapie_vs_eci.png (no .pdf; generated by
Benchmark_scripts/m2_ablations.py / generate_m2_report.py) is even earlier diagnostic-only content,
left untouched here -- Phase 1's float triage decides core/supplementary/internal-only for all of
this, not this script.

Output: paper_assets/provenance/<figure_basename>.json (one per figure)
Usage: python generate_figure_provenance.py
"""
from __future__ import annotations

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from paper_data import Evidence  # noqa: E402

V2_SCRIPT = "Benchmark_scripts/m2_generate_report_figures_v2.py"
T2_SCRIPT = "Benchmark_scripts/m2_generate_report_figures.py"

HYBRID_V2 = "Hybrid GRU-D v2"
GRUD_FAMILY_V2 = ["Temporal-Only GRU-D v2", "Frozen-Temporal Head Control v2", "Hybrid GRU-D v2"]
GRUD_FAMILY_T2 = ["Temporal-Only GRU-D", "Frozen-Temporal Head Control", "Hybrid GRU-D"]
ER_CSV = "m2_v2_eci_vs_recalibration.csv"


def _script_note(script: str, artifacts: list[str]) -> str:
    return f"generated by {script}, reading {', '.join(artifacts)} -- see this script's own docstring for scope"


def fig_headline_auroc_v2() -> None:
    ev = Evidence("fig1_headline_auroc_v2")
    ev.literal(V2_SCRIPT, reason=_script_note(V2_SCRIPT, ["m2_v2_results.csv", "m2_v2_deltas.json (CI fallback check)"]))
    # Same (artifact, filters, column) as table_headline_discrimination()'s primary-model row --
    # deliberately, so check_cross_asset_agreement independently confirms figure and table agree.
    ev.reduce_csv("mean", "m2_v2_results.csv", {"model": HYBRID_V2}, "auroc", fmt=".4f",
                   note="Hybrid GRU-D bar height, matches T1's own headline AUROC cell. Proxy cohort (MIMIC-IV-ED-derived).")
    ev.reduce_csv("std", "m2_v2_results.csv", {"model": HYBRID_V2}, "auroc", fmt=".4f", note="Hybrid GRU-D error bar.")
    ev.write_provenance()


def fig_calibration_v2() -> None:
    ev = Evidence("fig2_calibration_v2")
    ev.literal(V2_SCRIPT, reason=_script_note(V2_SCRIPT, ["m2_v2_predictions.csv"]))
    ev.literal("reliability diagram, 10-bin, all seeds pooled per model -- binning/pooling logic "
               "lives in the script above, not reproduced here (see this module's docstring)",
               reason="diagnostic multi-panel figure, no single headline scalar to cross-check "
               "against a table")
