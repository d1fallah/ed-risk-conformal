    # check_manifest_integrity actually hashes-verifies the raw predictions file this figure reads.
    ev.reduce_csv("len", "m2_v2_predictions.csv", {"model": HYBRID_V2}, "y_prob", fmt=",.0f",
                   note="row count backing the Hybrid GRU-D reliability panel (all 5 seeds pooled). "
                        "Proxy cohort (MIMIC-IV-ED-derived).")
    ev.write_provenance()


